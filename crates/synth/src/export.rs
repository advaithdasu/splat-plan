//! Export a synthetic scene in exactly the layout of a real capture, so the
//! whole pipeline (align → map → plan → verify) can be tested end to end.

use std::path::Path;

use colmap_io::Point3D;
use rand::{Rng, SeedableRng};
use rand_chacha::ChaCha8Rng;
use serde::{Deserialize, Serialize};
use splat_types::nalgebra::{Unit, UnitQuaternion};
use splat_types::{Similarity, Vec3};
use thiserror::Error;

use crate::scenes::SynthScene;

/// Errors writing an export.
#[derive(Debug, Error)]
pub enum ExportError {
    /// File system error.
    #[error("i/o: {0}")]
    Io(#[from] std::io::Error),
    /// PLY writing failed.
    #[error(transparent)]
    Ply(#[from] gs_io::PlyError),
    /// COLMAP writing failed.
    #[error(transparent)]
    Colmap(#[from] colmap_io::ColmapError),
    /// JSON serialization failed.
    #[error(transparent)]
    Json(#[from] serde_json::Error),
}

/// What the exporter knows that the pipeline must *not* read: the true
/// transform from the metric, Z-up scene frame to the exported "COLMAP" frame.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct GroundTruth {
    /// Scene name.
    pub scene: String,
    /// `x_colmap = sim(x_metric)`.
    pub metric_to_colmap: Similarity,
}

/// A random similarity imitating COLMAP's arbitrary frame: scale in
/// `[0.2, 5]`, uniformly random rotation, translation in `[-10, 10]³`.
pub fn random_similarity(seed: u64) -> Similarity {
    let mut rng = ChaCha8Rng::seed_from_u64(seed);
    let axis = Unit::new_normalize(Vec3::new(
        rng.gen_range(-1.0..1.0),
        rng.gen_range(-1.0..1.0),
        rng.gen_range(-1.0..1.0) + 1e-6,
    ));
    Similarity {
        scale: (rng.gen_range(0.2f64.ln()..5.0f64.ln())).exp(),
        rot: UnitQuaternion::from_axis_angle(&axis, rng.gen_range(0.0..std::f64::consts::PI)),
        trans: Vec3::new(
            rng.gen_range(-10.0..10.0),
            rng.gen_range(-10.0..10.0),
            rng.gen_range(-10.0..10.0),
        ),
    }
}

/// Writes `dir/splat/point_cloud.ply`, `dir/colmap/{cameras,images,points3D}.txt`,
/// `dir/ground_truth.json` and a `dir/capture.md` note, all in the frame given
/// by `metric_to_colmap`. If `write_scale` is set, also writes `dir/scale.json`
/// with the correct metric scale (as a human would after measuring).
pub fn export_capture(
    scene: &SynthScene,
    dir: impl AsRef<Path>,
    metric_to_colmap: &Similarity,
    write_scale: bool,
) -> Result<(), ExportError> {
    let dir = dir.as_ref();
    std::fs::create_dir_all(dir.join("splat"))?;
    let moved = scene
        .to_scene()
        .transformed(metric_to_colmap, splat_types::Scale::Unscaled);
    gs_io::write_ply(dir.join("splat/point_cloud.ply"), &moved.gaussians)?;

    // A sparse subset of Gaussian means stands in for COLMAP's SfM points.
    let points: Vec<Point3D> = moved
        .gaussians
        .iter()
        .step_by(37)
        .enumerate()
        .map(|(i, g)| {
            let c = g.color_rgb();
            Point3D {
                id: i as u64 + 1,
                xyz: g.mean_f64(),
                rgb: c.map(|v| (v * 255.0).round() as u8),
                error: 0.5,
            }
        })
        .collect();
    colmap_io::write_model(dir.join("colmap"), &moved.cameras, &points)?;

    let gt = GroundTruth {
        scene: scene.name.clone(),
        metric_to_colmap: *metric_to_colmap,
    };
    std::fs::write(
        dir.join("ground_truth.json"),
        serde_json::to_string_pretty(&gt)?,
    )?;
    if write_scale {
        let scale = serde_json::json!({
            "metric_scale": 1.0 / metric_to_colmap.scale,
            "method": "synthetic ground truth",
            "notes": "written by synth::export_capture",
        });
        std::fs::write(
            dir.join("scale.json"),
            serde_json::to_string_pretty(&scale)?,
        )?;
    }
    std::fs::write(
        dir.join("capture.md"),
        format!(
            "# {}\n\nSYNTHETIC capture generated by the `synth` crate (not real footage).\n",
            scene.name
        ),
    )?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::scenes::random_field;

    #[test]
    fn export_roundtrips_through_readers() {
        let s = random_field(3, 20);
        let sim = random_similarity(11);
        let dir = std::env::temp_dir().join(format!("synth-export-{}", std::process::id()));
        export_capture(&s, &dir, &sim, true).unwrap();
        let gs = gs_io::load_ply(dir.join("splat/point_cloud.ply")).unwrap();
        let model = colmap_io::load_model(dir.join("colmap")).unwrap();
        std::fs::remove_dir_all(&dir).unwrap();
        assert_eq!(gs.len(), s.gaussians.len());
        assert_eq!(model.images.len(), s.cameras.len());
        // Camera centers moved by the similarity.
        let c0 = sim.apply_point(&s.cameras[0].center());
        assert!((model.images[0].pose.center() - c0).norm() < 1e-6 * (1.0 + c0.norm()));
        let m0 = sim.apply_point(&s.gaussians[0].mean_f64());
        assert!((gs[0].mean_f64() - m0).norm() < 1e-4 * (1.0 + m0.norm()));
    }
}
